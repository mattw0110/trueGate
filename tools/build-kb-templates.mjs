#!/usr/bin/env node
// Snapshot ~/.truegate/* into src/cli/kb-templates.ts.
// Run this whenever the operator-wide reference content in ~/.truegate/ changes
// and you want to bundle the new content into the truegate binary.

import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const KB_ROOT = join(homedir(), '.truegate');
const OUT_FILE = join(__dirname, '..', 'src', 'cli', 'kb-templates.ts');

// Files to bundle. We exclude config.json (operator's secrets) and rules.yaml
// (operator's enforcement; comes from a different scaffold).
const SKIP = new Set(['config.json', 'rules.yaml']);

async function walk(dir) {
  const out = [];
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    if (SKIP.has(e.name)) continue;
    const full = join(dir, e.name);
    if (e.isDirectory()) {
      out.push(...(await walk(full)));
    } else if (e.isFile() && e.name.endsWith('.md')) {
      out.push(full);
    }
  }
  return out;
}

function escape(content) {
  // Use String.raw via JSON.stringify — safe for any UTF-8 content.
  return JSON.stringify(content);
}

const files = (await walk(KB_ROOT)).sort();
if (files.length === 0) {
  console.error('No .md files found under', KB_ROOT);
  process.exit(1);
}

const entries = [];
for (const path of files) {
  const rel = relative(KB_ROOT, path);
  const content = await readFile(path, 'utf-8');
  entries.push(`  ${escape(rel)}: ${escape(content)},`);
}

const banner = `// AUTOGENERATED by tools/build-kb-templates.mjs — do not edit by hand.
// Source: ~/.truegate/ as of ${new Date().toISOString()}
// Re-run \`node tools/build-kb-templates.mjs\` to refresh.
`;

const body = `${banner}
/**
 * Operator-wide governance knowledge-base templates bundled into the
 * truegate binary. The \`truegate kb-init\` command writes these files
 * into a target directory.
 *
 * Keys are paths relative to the destination root (e.g. \`topics/code-style.md\`).
 * Values are the file content verbatim.
 */
export const KB_TEMPLATES: Record<string, string> = {
${entries.join('\n')}
};
`;

await writeFile(OUT_FILE, body, 'utf-8');
const stats = await stat(OUT_FILE);
console.log(`Wrote ${files.length} files (${stats.size.toLocaleString()} bytes) → ${OUT_FILE}`);
